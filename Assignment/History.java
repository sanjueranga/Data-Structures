public class History {
    String pageName;
    String pageId;
    String Date;
    String url;
    boolean Bookmark;

    public History(String pageName, String pageId, String Date, String url, boolean Bookmark) {

        this.pageName = pageName;
        this.pageId = pageId;
        this.Date = Date;
        this.url = url;
        this.Bookmark = Bookmark;

    }
}
